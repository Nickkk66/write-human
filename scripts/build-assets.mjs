// Copies browser assets into public/vendor: the Motion animation library,
// the Inter font, and the Phosphor icons this page uses (as public/icons.js).
import { mkdir, copyFile, readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "public", "vendor");
await mkdir(out, { recursive: true });

await copyFile(join(root, "node_modules/motion/dist/motion.js"), join(out, "motion.js"));
await copyFile(join(root, "node_modules/motion/LICENSE.md"), join(out, "motion-LICENSE.md")).catch(() => {});
const fonts = join(root, "vendor/siwc-devkit/assets/fonts");
await copyFile(join(fonts, "inter-latin.woff2"), join(out, "inter-latin.woff2"));
await copyFile(join(fonts, "inter-OFL.txt"), join(out, "inter-OFL.txt"));
await copyFile(join(root, "node_modules/@phosphor-icons/core/LICENSE"), join(out, "phosphor-LICENSE.txt")).catch(() => {});
// ChatGPT sign-in artwork comes from OpenAI's DevKit (used under OpenAI's brand guidelines), not this repo.
for (const name of ["chatgpt-button-white-21.svg", "chatgpt-button-black-21.svg", "chatgpt-dialog-72.svg", "chatgpt-usage-20.svg"]) {
  await copyFile(join(root, "vendor/siwc-devkit/assets/brand", name), join(root, "public", name));
}

const ICONS = [
  "files", "file-text", "microphone-stage", "chart-bar", "sign-out", "magic-wand", "sparkle", "list-checks",
  "hash", "lock-key", "quotes", "chat-circle-text", "briefcase", "newspaper", "envelope-simple", "slack-logo",
  "linkedin-logo", "graduation-cap", "pen-nib", "plus", "copy", "check", "stop", "warning-circle", "lightbulb",
  "waveform", "caret-down", "dots-three", "trash", "question", "arrow-left", "shield-check", "books", "flask",
  "seal-check", "user-circle", "x", "magnifying-glass", "text-aa", "clock-counter-clockwise", "arrows-clockwise",
  "eye", "fingerprint", "target", "gauge", "pencil-simple-line", "note-pencil", "arrow-up-right", "arrow-square-out",
  "detective", "robot", "check-circle", "eye-slash", "plus-circle", "lightning", "crown", "currency-dollar", "infinity",
  "user-sound", "sliders", "scan", "text-t", "cursor-text", "arrow-right",
];
const icons = {};
for (const name of ICONS) {
  const svg = await readFile(join(root, "node_modules/@phosphor-icons/core/assets/duotone", `${name}-duotone.svg`), "utf8");
  icons[name] = svg.trim();
}
await writeFile(join(root, "public", "icons.js"),
  `// Generated by scripts/build-assets.mjs from @phosphor-icons/core (MIT license), duotone weight.\nexport const ICONS = ${JSON.stringify(icons)};\n`);
console.log(`Copied Motion, Inter, and ${ICONS.length} Phosphor icons.`);
